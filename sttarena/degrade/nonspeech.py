"""Hallucination set v2: clips without target speech, by group (robustness study, recommendation R6).

v1 has 300 clips of 8 kinds; 11 of 19 Arabic models emitted words on >= 98 % of them (10 on all), a quarter
of the clips were intelligible Arabic babble, and no per-kind rate was reported, so "any output" saturated and
mixed hallucination with transcribing real background speech. v2 records meta.group and meta.kind for
per-group rates (headline: macro over the non-speech groups) and keeps non-target speech in its own group, NT.

  G1  silence-like: digital zeros, line silence (white, -75..-65 dBov), comfort noise (pink, -60..-45),
      AGC-raised noise floor (brown, -45..-30), mains hum (-50..-30)
  G2  network tones (tones.py): ringback 50 %, busy 12.5 %, congestion 12.5 %, special information 6.25 %,
      call waiting 6.25 %, fax CNG 6.25 %, fax CED 6.25 %, at -20..-10 dBov; countries weighted Saudi 25 %,
      Egypt 20 %, UAE 10 %, 13 more Arab networks share the rest
  G3  DTMF: 4-16 digits, tones 65-250 ms, pauses 65-400 ms, ETSI ES 201 235-2 levels, over line silence
  G5  office / keyboard / printer / fan noise from the noise bank, -45..-25 dBov
  G7  environment without voices (home, outdoor, street, transport) from the noise bank, -45..-25 dBov
  NT  non-target speech: babble_v2 (8-16 far-field talkers from the disjoint pool), -40..-25 dBov
Clip counts follow R6 (G1 150, G2 160, G3 100, G5 120, G7 180, NT 120 per 830); G4 hold music, G6
non-lexical vocal sounds and G8 handling noise need corpora that are not wired in. Durations are allocated
30 % 1-4 s, 40 % 5-15 s, 30 % 20-30 s within every group. G2/G3 are generated by the network and pass only the
G.711 trunk and a recording format (always narrowband); half of the other clips go through the whole v2
telephone channel without level normalization (device response, access codec with DTX and losses, trunk,
recording format), the rest stay wideband. G1-G3 and their channels need no downloads; G5/G7 need the noise
bank and NT the talker pool, and are skipped without them.
"""

from __future__ import annotations

import numpy as np

from . import tones
from .chain import seed_for
from .chain_v2 import network_side, telephone
from .noise import NoiseBank, colored_noise, hum

GROUPS = {"G1": 150, "G2": 160, "G3": 100, "G5": 120, "G7": 180, "NT": 120}
KINDS: dict[str, dict[str, float]] = {
    "G1": {"zeros": 0.2, "line_silence": 0.2, "comfort_noise": 0.2, "agc_floor": 0.2, "hum": 0.2},
    "G2": {"ringback": 0.5, "busy": 0.125, "congestion": 0.125, "sit": 0.0625, "call_waiting": 0.0625,
           "fax_cng": 0.0625, "fax_ced": 0.0625},
    "G3": {"dtmf": 1.0},
    "NT": {"babble_v2": 1.0},
}
BANK_GROUPS = {"G5": ("office", "keyboard", "printer", "fan"),
               "G7": ("home", "outdoor", "street", "transport")}
NETWORK_GROUPS = ("G2", "G3")
DURATION_STRATA = ((0.3, 1.0, 4.0), (0.4, 5.0, 15.0), (0.3, 20.0, 30.0))
G1_LEVELS = {"line_silence": (-75, -65), "comfort_noise": (-60, -45), "agc_floor": (-45, -30),
             "hum": (-50, -30)}


def available_groups(bank: NoiseBank) -> list[str]:
    ok = []
    for g in GROUPS:
        has_clips = g not in BANK_GROUPS or any(c in bank.clips for c in BANK_GROUPS[g])
        if has_clips and (g != "NT" or bank.talkers):
            ok.append(g)
    return ok


def plan(lang: str, n: int, groups: list[str]) -> list[tuple[str, str, float]]:
    """(clip id, group, duration) for `n` clips at R6's group shares; ids and durations of a group do not
    depend on which other groups are built, and rows are interleaved in sha256 order of their ids."""
    total = sum(GROUPS.values())
    out = []
    for g in groups:
        count = int(round(n * GROUPS[g] / total))
        quota = np.array([p for p, _, _ in DURATION_STRATA]) * count
        alloc = np.floor(quota).astype(int)
        alloc[np.argsort(alloc - quota)[: count - alloc.sum()]] += 1  # largest remainder
        strata = np.repeat(np.arange(len(DURATION_STRATA)), alloc)
        np.random.default_rng(seed_for(lang, "noise_only_v2", g, "strata")).shuffle(strata)
        for k, s in enumerate(strata):
            _, lo, hi = DURATION_STRATA[s]
            rng = np.random.default_rng(seed_for(lang, "noise_only_v2", g, str(k), "duration"))
            out.append((f"noise_only_v2/{g}/{k}", g, round(float(rng.uniform(lo, hi)), 3)))
    return sorted(out, key=lambda r: seed_for(r[0]))


def _source(group: str, sec: float, rng: np.random.Generator,
            bank: NoiseBank) -> tuple[np.ndarray, int, str, dict]:
    """(audio, sample rate, kind, params) before any channel."""
    if group in BANK_GROUPS:
        cats = [c for c in BANK_GROUPS[group] if c in bank.clips]
        kind, level = cats[int(rng.integers(len(cats)))], float(rng.uniform(-45, -25))
        n = int(round(sec * 16000))
        x, drawn = bank.noise_v2(kind, n, rng)
        return x * np.float32(10 ** (level / 20)), 16000, kind, {"level_dbov": round(level, 1), **drawn}
    keys = list(KINDS[group])
    p = np.array([KINDS[group][k] for k in keys])
    kind = keys[int(rng.choice(len(keys), p=p / p.sum()))]
    sr = 8000 if group in NETWORK_GROUPS else 16000
    n = int(round(sec * sr))
    if kind == "zeros":
        return np.zeros(n, dtype=np.float32), sr, kind, {}
    if kind == "babble_v2":
        x, drawn = bank.babble_v2(n, rng)
        level = float(rng.uniform(-40, -25))
        return x * np.float32(10 ** (level / 20)), sr, kind, {"level_dbov": round(level, 1), **drawn}
    if group == "G1":
        level = float(rng.uniform(*G1_LEVELS[kind]))
        base = hum(n, rng, sr) if kind == "hum" else \
            colored_noise(n, rng, {"line_silence": 0.0, "comfort_noise": 1.0, "agc_floor": 2.0}[kind])
        return base * np.float32(10 ** (level / 20)), sr, kind, {"level_dbov": round(level, 1)}
    floor_db = float(rng.uniform(-75, -65))
    floor = colored_noise(n, rng, 0.0) * np.float32(10 ** (floor_db / 20))
    if kind == "dtmf":
        tone_s, gap_s = float(rng.uniform(0.065, 0.25)), float(rng.uniform(0.065, 0.4))
        k = int(np.clip(int(rng.integers(4, 17)), 1, max(1, int(sec / (tone_s + gap_s)))))
        digits = "".join(rng.choice(list("0123456789*#"), size=k))
        row_db, col_db = (float(rng.uniform(-1, 1)) + v for v in (tones.DTMF_ROW_DBOV, tones.DTMF_COL_DBOV))
        burst = tones.dtmf(digits, sr, tone_s, gap_s, row_db, col_db)[:n]
        start = int(rng.integers(0, n - len(burst) + 1))
        floor[start: start + len(burst)] += burst
        return floor, sr, kind, {"digits": digits, "tone_ms": round(1000 * tone_s),
                                 "gap_ms": round(1000 * gap_s), "row_dbov": round(row_db, 2),
                                 "col_dbov": round(col_db, 2), "floor_dbov": round(floor_db, 1)}
    level = float(rng.uniform(-20, -10))
    if kind == "fax_ced":
        return floor + tones.fax_ced(sec, sr, rng, level)[:n], sr, kind, {"level_dbov": round(level, 1),
                                                                         "floor_dbov": round(floor_db, 1)}
    country, spec, cadence = tones.tone_plan(rng, kind)
    x = tones.tone(spec, cadence, sec, sr, rng, level)[:n]
    return floor + x, sr, kind, {"country": country, "tone_spec": spec, "cadence_s": list(cadence),
                                 "level_dbov": round(level, 1), "floor_dbov": round(floor_db, 1)}


def clip(lang: str, clip_id: str, group: str, sec: float, bank: NoiseBank) -> tuple[np.ndarray, int, dict]:
    """One hallucination-v2 clip: (audio, sample rate, meta with kind, group and degradation)."""
    seed = seed_for(lang, clip_id)
    rng = np.random.default_rng(seed_for(str(seed), "source"))
    x, sr, kind, params = _source(group, sec, rng, bank)
    if group in NETWORK_GROUPS:
        x, sr, channel = network_side(x, sr, seed)
    elif np.random.default_rng(seed_for(str(seed), "phone")).random() < 0.5:
        x, sr, channel = telephone(x, sr, seed, set_level=False)
    else:
        channel = {"band": "wb"}
    meta = {"kind": kind, "group": group,
            "degradation": {"chain_version": 2, "chain": "nonspeech", "duration_s": sec, **params, **channel}}
    return np.clip(x, -1, 1).astype(np.float32), sr, meta
